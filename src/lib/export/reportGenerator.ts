/**
 * Report Generator — Client-side PDF and CSV export for flow analysis.
 *
 * PDF: Branded Stelthion report with cover, floorplan screenshot,
 *      zone visitor table, optional flow analysis, and LLM narrative.
 * CSV: Raw tabular data download.
 */

import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import html2canvas from 'html2canvas';
import type { IdeaparkZone, ZoneVisitorData } from '@/lib/data/ideaparkZones';
import type { FlowQueryResponse } from '@/lib/types/flowQuery';

// ─── Types ────────────────────────────────────────────────────────────────────

export interface ReportZone {
  zone: IdeaparkZone;
  visitors: ZoneVisitorData;
}

export interface ReportParams {
  mallId: string;
  mallName: string;
  /** Brand identity colors */
  colors: {
    primary: string;      // e.g. '#328d2e'
    secondary: string;
    accent: string;       // e.g. '#214990'
    gradientFrom: string; // e.g. '#264d21'
    gradientTo: string;
  };
  floor: string;
  hour: number;
  dayOfWeek: number;
  zones: ReportZone[];
  /** DOM element containing the SVG floorplan for screenshot */
  floorplanElement?: HTMLElement | null;
  /** Flow query results, if user ran one */
  flowQuery?: FlowQueryResponse | null;
  /** LLM-generated narrative, if available */
  narrative?: { narrative: string; highlights: string[] } | null;
  /** Locale for labels */
  locale?: string;
}

// ─── Color helpers ────────────────────────────────────────────────────────────

function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  return [
    parseInt(h.substring(0, 2), 16),
    parseInt(h.substring(2, 4), 16),
    parseInt(h.substring(4, 6), 16),
  ];
}

// ─── PDF Generation ───────────────────────────────────────────────────────────

export async function generateFlowReportPDF(params: ReportParams): Promise<void> {
  const {
    mallName,
    colors,
    floor,
    hour,
    zones,
    floorplanElement,
    flowQuery,
    narrative,
  } = params;

  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();   // 297
  const pageH = doc.internal.pageSize.getHeight();  // 210
  const margin = 15;

  const primary = hexToRgb(colors.primary);
  const accent = hexToRgb(colors.accent);
  const gradFrom = hexToRgb(colors.gradientFrom);

  const now = new Date();
  const dateStr = now.toLocaleDateString('fi-FI', { day: '2-digit', month: 'short', year: 'numeric' });
  const timeStr = now.toLocaleTimeString('fi-FI', { hour: '2-digit', minute: '2-digit' });

  // ── Helper: page footer ──
  const addFooter = (pageNum: number) => {
    doc.setFontSize(7);
    doc.setTextColor(160, 160, 160);
    doc.text(
      `Generated by Stelthion Analytics Platform · ${dateStr} ${timeStr}`,
      margin, pageH - 8,
    );
    doc.text(`${pageNum}`, pageW - margin, pageH - 8, { align: 'right' });
  };

  // ── Helper: page header bar ──
  const addHeader = (title: string) => {
    doc.setFillColor(...gradFrom);
    doc.rect(0, 0, pageW, 18, 'F');
    doc.setFontSize(11);
    doc.setTextColor(255, 255, 255);
    doc.text(title, margin, 12);
    doc.setFontSize(8);
    doc.text(mallName, pageW - margin, 12, { align: 'right' });
  };

  // ═══════════════════════════════════════════════════════════════════════════
  // PAGE 1: Cover
  // ═══════════════════════════════════════════════════════════════════════════

  // Full-page gradient background
  doc.setFillColor(...gradFrom);
  doc.rect(0, 0, pageW, pageH, 'F');

  // Accent stripe
  doc.setFillColor(...primary);
  doc.rect(0, pageH - 30, pageW, 30, 'F');

  // Title
  doc.setFontSize(32);
  doc.setTextColor(255, 255, 255);
  doc.text('Visitor Flow Analysis', margin, 60);
  doc.text('Report', margin, 75);

  // Mall name
  doc.setFontSize(18);
  doc.setTextColor(200, 230, 200);
  doc.text(mallName, margin, 95);

  // Details
  doc.setFontSize(12);
  doc.setTextColor(180, 210, 180);
  const floorLabel = floor === 'upper' ? 'Upper Floor' : 'Ground Floor';
  doc.text(`${floorLabel}  ·  ${hour}:00`, margin, 110);
  doc.text(dateStr, margin, 120);

  // Stelthion branding
  doc.setFontSize(10);
  doc.setTextColor(255, 255, 255);
  doc.text('STELTHION', margin, pageH - 15);
  doc.setFontSize(7);
  doc.text('Analytics Platform', margin, pageH - 10);

  addFooter(1);

  // ═══════════════════════════════════════════════════════════════════════════
  // PAGE 2: Executive Summary (LLM narrative or fallback)
  // ═══════════════════════════════════════════════════════════════════════════

  doc.addPage();
  addHeader('Executive Summary');
  let cursorY = 28;

  const totalVisitors = zones.reduce((s, z) => s + z.visitors.visitors, 0);
  const sortedByVisitors = [...zones].sort((a, b) => b.visitors.visitors - a.visitors.visitors);
  const top3 = sortedByVisitors.slice(0, 3);

  if (narrative?.narrative) {
    // LLM-generated narrative
    doc.setFontSize(10);
    doc.setTextColor(40, 40, 40);
    const lines = doc.splitTextToSize(narrative.narrative, pageW - margin * 2);
    doc.text(lines, margin, cursorY);
    cursorY += lines.length * 5 + 8;

    if (narrative.highlights?.length > 0) {
      doc.setFontSize(9);
      doc.setFont('helvetica', 'bold');
      doc.text('Key Highlights', margin, cursorY);
      cursorY += 6;
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(60, 60, 60);
      for (const h of narrative.highlights) {
        const bulletLines = doc.splitTextToSize(`•  ${h}`, pageW - margin * 2 - 5);
        doc.text(bulletLines, margin + 3, cursorY);
        cursorY += bulletLines.length * 4.5 + 2;
      }
    }
  } else {
    // Fallback template summary
    doc.setFontSize(10);
    doc.setTextColor(40, 40, 40);
    const fallback = [
      `At ${hour}:00, a total of ${totalVisitors.toLocaleString()} visitors were recorded across ${zones.length} zones on the ${floorLabel.toLowerCase()}.`,
      '',
      `The busiest zones were ${top3.map(z => `${z.zone.nameFi ?? z.zone.name} (${z.visitors.visitors})`).join(', ')}.`,
      '',
      `Average density across all zones: ${(zones.reduce((s, z) => s + z.visitors.density, 0) / zones.length).toFixed(3)} visitors/m².`,
    ].join('\n');
    const lines = doc.splitTextToSize(fallback, pageW - margin * 2);
    doc.text(lines, margin, cursorY);
    cursorY += lines.length * 5 + 8;
  }

  // KPI boxes
  cursorY += 5;
  const kpiBoxW = 60;
  const kpiBoxH = 22;
  const kpis = [
    { label: 'Total Visitors', value: totalVisitors.toLocaleString() },
    { label: 'Zones', value: `${zones.length}` },
    { label: 'Busiest Zone', value: top3[0]?.zone.nameFi ?? '—' },
  ];

  kpis.forEach((kpi, i) => {
    const x = margin + i * (kpiBoxW + 8);
    doc.setFillColor(248, 246, 243);
    doc.roundedRect(x, cursorY, kpiBoxW, kpiBoxH, 3, 3, 'F');
    doc.setFontSize(7);
    doc.setTextColor(120, 120, 120);
    doc.text(kpi.label, x + 5, cursorY + 7);
    doc.setFontSize(14);
    doc.setTextColor(...primary);
    doc.text(kpi.value, x + 5, cursorY + 17);
  });

  addFooter(2);

  // ═══════════════════════════════════════════════════════════════════════════
  // PAGE 3: Floorplan Screenshot
  // ═══════════════════════════════════════════════════════════════════════════

  if (floorplanElement) {
    try {
      const canvas = await html2canvas(floorplanElement, {
        scale: 2,
        backgroundColor: '#F8F6F3',
        useCORS: true,
        logging: false,
      });

      doc.addPage();
      addHeader(`Floor Plan — ${floorLabel} at ${hour}:00`);

      const imgData = canvas.toDataURL('image/png');
      const imgAspect = canvas.width / canvas.height;
      const availW = pageW - margin * 2;
      const availH = pageH - 30 - margin; // below header, above footer
      let imgW = availW;
      let imgH = imgW / imgAspect;
      if (imgH > availH) {
        imgH = availH;
        imgW = imgH * imgAspect;
      }
      const imgX = margin + (availW - imgW) / 2;
      doc.addImage(imgData, 'PNG', imgX, 22, imgW, imgH);

      addFooter(3);
    } catch {
      // html2canvas can fail in some environments; skip the page
    }
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // PAGE 4: Zone Visitor Table
  // ═══════════════════════════════════════════════════════════════════════════

  doc.addPage();
  addHeader(`Zone Visitor Summary — ${hour}:00`);

  const tableBody = sortedByVisitors.map((z) => [
    z.zone.nameFi ?? z.zone.name,
    z.zone.category,
    z.visitors.visitors.toLocaleString(),
    z.visitors.density.toFixed(3),
    `${Math.round((z.visitors.visitors / z.zone.capacity) * 100)}%`,
    `${z.visitors.delta >= 0 ? '+' : ''}${z.visitors.delta}%`,
  ]);

  autoTable(doc, {
    startY: 22,
    margin: { left: margin, right: margin },
    head: [['Zone', 'Category', 'Visitors', 'Density (p/m²)', 'Capacity %', 'Δ vs Plan']],
    body: tableBody,
    headStyles: {
      fillColor: primary,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
    },
    bodyStyles: { fontSize: 8 },
    alternateRowStyles: { fillColor: [248, 246, 243] },
    styles: { cellPadding: 3 },
  });

  addFooter(floorplanElement ? 4 : 3);

  // ═══════════════════════════════════════════════════════════════════════════
  // PAGE 5 (optional): Flow Analysis
  // ═══════════════════════════════════════════════════════════════════════════

  if (flowQuery && flowQuery.edges.length > 0) {
    doc.addPage();
    addHeader('Flow Analysis');

    let y = 26;

    // Flow summary
    doc.setFontSize(10);
    doc.setTextColor(40, 40, 40);
    doc.setFont('helvetica', 'bold');
    doc.text(`${flowQuery.direction.toUpperCase()} — ${flowQuery.originName}`, margin, y);
    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text(`Total visitors: ${flowQuery.totalVisitors.toLocaleString()}`, margin, y);
    y += 8;

    // Narrative
    const narrativeText = flowQuery.narrativeFi || flowQuery.narrativeEn;
    if (narrativeText) {
      doc.setTextColor(80, 80, 80);
      const narrativeLines = doc.splitTextToSize(narrativeText, pageW - margin * 2);
      doc.text(narrativeLines, margin, y);
      y += narrativeLines.length * 4.5 + 6;
    }

    // Flow edges table
    const flowBody = flowQuery.edges.map((e) => [
      e.fromName,
      e.toName,
      e.visitors.toLocaleString(),
      `${(e.share * 100).toFixed(1)}%`,
    ]);

    autoTable(doc, {
      startY: y,
      margin: { left: margin, right: margin },
      head: [['From', 'To', 'Visitors', 'Share']],
      body: flowBody,
      headStyles: {
        fillColor: accent,
        textColor: [255, 255, 255],
        fontStyle: 'bold',
        fontSize: 8,
      },
      bodyStyles: { fontSize: 8 },
      alternateRowStyles: { fillColor: [248, 246, 243] },
      styles: { cellPadding: 3 },
    });

    addFooter(floorplanElement ? 5 : 4);
  }

  // ── Download ──
  const safeName = mallName.replace(/[^a-zA-Z0-9]/g, '-').toLowerCase();
  doc.save(`stelthion-report-${safeName}-${floor}-${hour}00.pdf`);
}

// ─── CSV Generation ───────────────────────────────────────────────────────────

export function generateFlowReportCSV(params: ReportParams): void {
  const { mallName, floor, hour, zones, flowQuery } = params;
  const rows: string[] = [];

  // Zone data header
  rows.push('Zone,Zone (FI),Category,Floor,Hour,Visitors,Predicted,Delta %,Density (p/m²),Capacity,Capacity %');

  for (const z of zones) {
    const capPct = Math.round((z.visitors.visitors / z.zone.capacity) * 100);
    rows.push([
      csvEscape(z.zone.name),
      csvEscape(z.zone.nameFi),
      z.zone.category,
      floor,
      hour,
      z.visitors.visitors,
      z.visitors.predicted,
      z.visitors.delta,
      z.visitors.density.toFixed(3),
      z.zone.capacity,
      capPct,
    ].join(','));
  }

  // Flow edges (if present)
  if (flowQuery && flowQuery.edges.length > 0) {
    rows.push('');
    rows.push('Flow From,Flow To,Visitors,Share %');
    for (const e of flowQuery.edges) {
      rows.push([
        csvEscape(e.fromName),
        csvEscape(e.toName),
        e.visitors,
        (e.share * 100).toFixed(1),
      ].join(','));
    }
  }

  const blob = new Blob([rows.join('\n')], { type: 'text/csv;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  const safeName = mallName.replace(/[^a-zA-Z0-9]/g, '-').toLowerCase();
  a.href = url;
  a.download = `stelthion-data-${safeName}-${floor}-${hour}00.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

function csvEscape(val: string): string {
  if (val.includes(',') || val.includes('"') || val.includes('\n')) {
    return `"${val.replace(/"/g, '""')}"`;
  }
  return val;
}
